/// Screenshot gallery: renders every scene in [scenes] at phone size
/// (390 x 844, dark theme, the app's only theme) and writes PNGs to
/// docs/review/screenshots/widgets/ plus the index docs/review/gallery.md.
///
/// Run: `flutter test --tags gallery test/gallery/gallery_test.dart`
/// (excluded from the normal suite by dart_test.yaml).
const _out = '../docs/review/screenshots/widgets';

void main() {
  setUpAll(loadGalleryFonts);
  final shots = <({Scene scene, double scale, String file})>[];

  for (final scene in scenes) {
    for (final scale in scene.textScales) {
      final suffix = scale == 1.0 ? '' : '@text${scale.toStringAsFixed(0)}x';
      final file = '${scene.name}$suffix.png';
      testWidgets('${scene.name} text x$scale', (t) async {
        final handle = t.ensureSemantics();
        final g = await pumpGallery(t, scene.world(), textScale: scale);
        await scene.act(g);
        if (!scene.settleAnimations) await g.settle(animations: false);
        await captureTo(t, '$_out/$file');
        expect(t.takeException(), isNull);
        shots.add((scene: scene, scale: scale, file: file));
        handle.dispose();
      });
    }
  }

  tearDownAll(() => _writeIndex(shots));
}

void _writeIndex(List<({Scene scene, double scale, String file})> shots) {
  if (shots.isEmpty) return;
  final b = StringBuffer()
    ..writeln('# Widget screenshot gallery')
    ..writeln()
    ..writeln(
      'Generated by `app/test/gallery/gallery_test.dart` (run '
      '`cd app && flutter test --tags gallery test/gallery/gallery_test.dart`). '
      'Every image is the real app (real router, screens and theme) '
      'rendered in a widget test against a fake API with sample data, '
      'at 390 x 844 pt (the handoff frame), 1 px per pt. The app has a '
      'single dark theme, so there is no light variant. Key screens are '
      'also shown at text scale 2.0. Photos are generated gradients. '
      'Accessibility results for the same scenes: [a11y-audit.md](a11y-audit.md).',
    )
    ..writeln();
  String? group;
  for (final s in shots) {
    if (s.scene.group != group) {
      group = s.scene.group;
      b
        ..writeln('## $group')
        ..writeln();
    }
    final scale = s.scale == 1.0 ? '' : ' (text scale ${s.scale})';
    b
      ..writeln('### `${s.scene.name}`$scale')
      ..writeln()
      ..writeln('${s.scene.caption}')
      ..writeln()
      ..writeln(
        '<img src="screenshots/widgets/${s.file}" width="260" '
        'alt="${s.scene.name}$scale">',
      )
      ..writeln();
  }
  File('../docs/review/gallery.md').writeAsStringSync(b.toString());
}
