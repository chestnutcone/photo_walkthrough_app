library;

import 'dart:io';

import 'package:flutter/rendering.dart';
import 'package:flutter_test/flutter_test.dart';

import 'support/gallery_fonts.dart';
import 'support/gallery_harness.dart';
import 'support/scenes.dart';

/// Accessibility audit over every gallery scene: Flutter's four guideline
/// matchers plus a semantics check (every tappable node is labelled) and the
/// reading order (traversal order of the labels). Failures must be listed in
/// [knownFailures] with a reason, or the test fails. Writes
/// docs/review/a11y-audit.md.
///
/// Run: `flutter test --tags gallery --run-skipped test/gallery/a11y_audit_test.dart`
final guidelines = <String, AccessibilityGuideline>{
  'android 48pt': androidTapTargetGuideline,
  'iOS 44pt': iOSTapTargetGuideline,
  'labelled': labeledTapTargetGuideline,
  'contrast': textContrastGuideline,
};

const _segments =
    'Progress segments are 3 pt bars in a 15 pt band (ruling S2-6, '
    'a11y-triage note B); the same action is on the 48 pt tap zones, pins '
    'and the Previous/Next chapter semantics buttons.';
const _photo =
    'Text over the photograph: the guideline samples photo pixels behind '
    'the chrome text (a11y-triage note C). Token colours pass 4.5:1.';

/// scene -> guideline -> reason. Anything else that fails is a defect.
const knownFailures = <String, Map<String, String>>{};

class Result {
  Result(this.scene, this.outcomes, this.order);
  final Scene scene;
  final Map<String, String?> outcomes; // null = pass, else reason text
  final List<String> order;
}

void main() {
  setUpAll(loadGalleryFonts);
  final results = <Result>[];

  for (final scene in scenes) {
    testWidgets('a11y ${scene.name}', (t) async {
      final handle = t.ensureSemantics();
      final g = await pumpGallery(t, scene.world());
      await scene.act(g);
      if (!scene.settleAnimations) await g.settle(animations: false);

      final outcomes = <String, String?>{};
      for (final e in guidelines.entries) {
        final eval = await e.value.evaluate(t);
        outcomes[e.key] = eval.passed ? null : eval.reason;
      }
      results.add(Result(scene, outcomes, _readingOrder(t)));
      handle.dispose();

      final unexpected = {
        for (final e in outcomes.entries)
          if (e.value != null &&
              knownFailures[scene.name]?.containsKey(e.key) != true)
            e.key: e.value,
      };
      expect(unexpected, isEmpty, reason: scene.name);
    });
  }

  tearDownAll(() => _write(results));
}

/// Labels in traversal order (what a screen reader steps through).
List<String> _readingOrder(WidgetTester t) {
  final root = t.binding.pipelineOwner.semanticsOwner?.rootSemanticsNode;
  final out = <String>[];
  void visit(SemanticsNode n) {
    final d = n.getSemanticsData();
    final label = d.label.replaceAll('\n', ' ').trim();
    if (label.isNotEmpty) out.add(label);
    for (final c in n.debugListChildrenInOrder(
      DebugSemanticsDumpOrder.traversalOrder,
    )) {
      visit(c);
    }
  }

  if (root != null) visit(root);
  return out;
}

void _write(List<Result> results) {
  if (results.isEmpty) return;
  final b = StringBuffer()
    ..writeln('# Accessibility audit (widget level)')
    ..writeln()
    ..writeln(
      'Generated by `app/test/gallery/a11y_audit_test.dart` on '
      '${DateTime.now().toUtc().toIso8601String().substring(0, 10)} '
      '(`cd app && flutter test --tags gallery --run-skipped '
      'test/gallery/a11y_audit_test.dart`). Every scene of the '
      '[screenshot gallery](gallery.md) (390 x 844 pt, text scale 1.0, '
      'real router and screens, fake API) is checked with Flutter\'s '
      '`androidTapTargetGuideline` (48 pt), `iOSTapTargetGuideline` (44 pt), '
      '`labeledTapTargetGuideline` (every tappable node has a label) and '
      '`textContrastGuideline` (pixel-sampled WCAG AA). A failure that is '
      'not listed with a reason in `knownFailures` fails the test. The '
      'on-device run of the same guidelines is `app/integration_test/'
      'g_a11y_test.dart` (see [e2e-report.md](e2e-report.md)); manual '
      'findings and fixes are in the hand-written section at the end.',
    )
    ..writeln()
    ..writeln('## Summary (screen x guideline)')
    ..writeln()
    ..writeln('| Screen | ${guidelines.keys.join(' | ')} |')
    ..writeln('|---|${guidelines.keys.map((_) => '---').join('|')}|');
  for (final r in results) {
    final cells = guidelines.keys.map((k) {
      if (r.outcomes[k] == null) return 'pass';
      return 'fail (known)';
    });
    b.writeln('| `${r.scene.name}` | ${cells.join(' | ')} |');
  }
  final known = results.where((r) => r.outcomes.values.any((v) => v != null));
  b
    ..writeln()
    ..writeln('## Known failures and why they are not fixed')
    ..writeln();
  if (known.isEmpty) b.writeln('None.');
  for (final r in known) {
    for (final e in r.outcomes.entries.where((e) => e.value != null)) {
      final why = knownFailures[r.scene.name]?[e.key] ?? 'UNEXPECTED';
      final first = e.value!.split('\n').first;
      b.writeln('- `${r.scene.name}` / ${e.key}: $why Measured: "$first"');
    }
  }
  b
    ..writeln()
    ..writeln('## Reading order (screen-reader traversal, first 14 labels)')
    ..writeln();
  for (final r in results) {
    final shown = r.order.take(14).map((s) {
      final short = s.length > 40 ? '${s.substring(0, 40)}…' : s;
      return short.replaceAll('|', '/');
    });
    b.writeln('- `${r.scene.name}`: ${shown.join(' → ')}');
  }
  final manual = File('test/gallery/a11y_audit_manual.md');
  if (manual.existsSync()) {
    b
      ..writeln()
      ..write(manual.readAsStringSync());
  }
  File('../docs/review/a11y-audit.md').writeAsStringSync(b.toString());
}
